#!/usr/bin/env node
// =============================================================================
// THE RECORD MATCHES THE CODE.
//
// The executive review of 29 September 2026 found fourteen places where the
// governing documents contradicted each other or the repository. The most
// load-bearing was IMPLEMENTATION_STATE's "Verified now": it said 358
// migrations with 322 the highest when the truth was 401 and 365, and it had
// said so, stale, for eleven days. Job counts were stated as 73, 75 and 88 in
// three places; the truth was 78. The decisions file's header said "thirteen
// answered, five pending" over a body with about twenty open items, and three
// of its section labels collided with its own numbering.
//
// A reminder to update a document is a belief, and it fails. So the counts are
// GENERATED from the repository into marked blocks, and this gate fails when a
// block disagrees with what the repository holds now — and when the decisions
// file breaks its own numbering. `--write` regenerates both blocks.
//
//   node scripts/check-record-matches-code.mjs            check
//   node scripts/check-record-matches-code.mjs --write    regenerate
//   --decisions <file>                                    check another decisions file (tests)
// =============================================================================
import { readFileSync, readdirSync, writeFileSync } from 'fs';
import { dirname, join, resolve } from 'path';
import { fileURLToPath } from 'url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const WRITE = args.includes('--write');
const decisionsArg = args.indexOf('--decisions');
const STATE = join(ROOT, 'docs/foundry-institution/IMPLEMENTATION_STATE.md');
const DECISIONS = decisionsArg >= 0 ? resolve(args[decisionsArg + 1]) : join(ROOT, 'docs/foundry-institution/OWNER_DECISIONS_PENDING.md');

// ─── What the repository holds ───────────────────────────────────────────────

function cadence(expr) {
  const [min, hour, dom, , dow] = expr.trim().split(/\s+/);
  if (dow !== '*') return 'weekly';
  if (dom !== '*') return 'monthly';
  if (hour === '*' && /[/,*]/.test(min)) return 'every few minutes';
  if (hour === '*') return 'hourly';
  if (/[/,]/.test(hour)) return 'every few hours';
  return 'daily';
}

function facts() {
  const migrations = readdirSync(join(ROOT, 'src/db/migrations')).filter((f) => f.endsWith('.sql'));
  const numbers = migrations.map((f) => Number(f.slice(0, f.indexOf('_'))));
  const dupes = new Set(numbers.filter((n, i) => numbers.indexOf(n) !== i)).size;
  const snapshot = readFileSync(join(ROOT, 'docs/db/schema.snapshot.sql'), 'utf8');
  const tables = (snapshot.match(/^CREATE TABLE /gm) ?? []).length;
  const jobsSrc = readFileSync(join(ROOT, 'src/jobs/index.ts'), 'utf8');
  const registry = jobsSrc.slice(jobsSrc.indexOf('export const JOB_REGISTRY'));
  const schedules = [...registry.matchAll(/\bschedule:\s*'([^']+)'/g)].map((m) => m[1]);
  const byCadence = {};
  for (const s of schedules) byCadence[cadence(s)] = (byCadence[cadence(s)] ?? 0) + 1;
  const order = ['every few minutes', 'hourly', 'every few hours', 'daily', 'weekly', 'monthly'];
  const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
  const seen = new Set(); const gates = new Set();
  const walk = (name) => {
    if (seen.has(name) || !pkg.scripts[name]) return;
    seen.add(name);
    const body = pkg.scripts[name];
    for (const m of body.matchAll(/npm run ([\w:-]+)/g)) walk(m[1]);
    for (const m of body.matchAll(/node (scripts\/[\w./-]+\.mjs)/g)) gates.add(m[1]);
  };
  walk('check');
  return [
    ['Migration files', String(migrations.length)],
    ['Highest migration number', String(Math.max(...numbers))],
    ['Migration numbers used more than once (historical, ratcheted)', String(dupes)],
    ['Tables in the schema snapshot', String(tables)],
    ['Scheduled jobs', `${String(schedules.length)}: ${order.filter((k) => byCadence[k]).map((k) => `${String(byCadence[k])} ${k}`).join(', ')}`],
    ['Scripts `npm run check` runs', String(gates.size)],
  ];
}

const FACTS_BEGIN = '<!-- facts:begin — generated by node scripts/check-record-matches-code.mjs --write; a gate fails when this disagrees with the repository -->';
const FACTS_END = '<!-- facts:end -->';
const factsBlock = () => [FACTS_BEGIN, '| Fact | Now |', '|---|---|',
  ...facts().map(([k, v]) => `| ${k} | ${v} |`), FACTS_END].join('\n');

// ─── The decisions file keeps its own numbering ──────────────────────────────

const OPEN = /\*\*(OWNER ACTION|OWNER|COUNSEL)\b/;
const CLOSED = /\*\*(DECIDED|SUPERSEDED)\b/;

function decisions(text) {
  const problems = [];
  const heads = [...text.matchAll(/^## (.+)$/gm)].map((m) => m[1]);
  const seen = { PENDING: new Set(), RESOLVED: new Set() };
  const open = []; const counsel = []; const decided = [];
  for (const h of heads) {
    if (/^§\d+/.test(h)) problems.push(`a "§n" label collides with the numbering: "## ${h.slice(0, 60)}"`);
    const m = /^(PENDING|RESOLVED)(?: (\d+))?\b/.exec(h);
    if (!m) continue;
    if (!m[2]) { problems.push(`${m[1]} with no number: "## ${h.slice(0, 60)}"`); continue; }
    const n = Number(m[2]);
    if (seen[m[1]].has(n)) problems.push(`${m[1]} ${String(n)} is used twice`);
    seen[m[1]].add(n);
    if (m[1] === 'PENDING') {
      const o = OPEN.exec(h); const c = CLOSED.exec(h);
      if (!o && !c) problems.push(`PENDING ${String(n)} carries no status (OWNER, OWNER ACTION, COUNSEL, DECIDED or SUPERSEDED)`);
      else if (c) decided.push(n);
      else if (o[1] === 'COUNSEL') counsel.push(n);
      else open.push(n);
    }
  }
  const list = (a) => a.map((n) => String(n)).join(', ') || 'none';
  const block = [
    '<!-- status:begin — generated from the headings below by node scripts/check-record-matches-code.mjs --write -->',
    `# ${String(open.length)} WAITING ON THE OWNER, ${String(counsel.length)} WITH COUNSEL, ${String(decided.length)} DECIDED IN PLACE`,
    '',
    `- **Waiting on the owner:** PENDING ${list(open)}.`,
    `- **Waiting on counsel:** PENDING ${list(counsel)} (interim positions in force; see below).`,
    `- **Decided, and kept where they were asked:** PENDING ${list(decided)}.`,
    `- **Answered and recorded as RESOLVED:** ${String(seen.RESOLVED.size)}.`,
    '<!-- status:end -->',
  ].join('\n');
  return { problems, block };
}

// ─── Check, or write ─────────────────────────────────────────────────────────

function between(text, begin, endMark) {
  const a = text.indexOf(begin); const b = text.indexOf(endMark);
  return a < 0 || b < 0 ? null : { a, b: b + endMark.length, body: text.slice(a, b + endMark.length) };
}

const failures = [];
let state = readFileSync(STATE, 'utf8');
const f = factsBlock();
const fs0 = between(state, '<!-- facts:begin', FACTS_END);
if (!fs0) failures.push('IMPLEMENTATION_STATE.md has no generated facts block');
else if (fs0.body !== f) {
  if (WRITE) { state = state.slice(0, fs0.a) + f + state.slice(fs0.b); writeFileSync(STATE, state); }
  else failures.push('IMPLEMENTATION_STATE.md\'s facts disagree with the repository');
}

let dec = readFileSync(DECISIONS, 'utf8');
const d = decisions(dec);
for (const p of d.problems) failures.push('decisions: ' + p);
const ds0 = between(dec, '<!-- status:begin', '<!-- status:end -->');
if (!ds0) failures.push('the decisions file has no generated status block');
else if (ds0.body !== d.block) {
  if (WRITE) { dec = dec.slice(0, ds0.a) + d.block + dec.slice(ds0.b); writeFileSync(DECISIONS, dec); }
  else failures.push('the decisions file\'s status header disagrees with its own headings');
}

const left = WRITE ? failures.filter((x) => !/disagree/.test(x)) : failures;
if (left.length) {
  console.error('The record does not match the code:\n');
  for (const x of left) console.error(`  ${x}`);
  console.error('\nRegenerate the blocks with `node scripts/check-record-matches-code.mjs --write`; fix a heading by hand.');
  process.exit(1);
}
console.log(WRITE ? '✓ record blocks regenerated from the repository'
  : '✓ the record matches the code (facts and decision status generated, numbering unique)');
